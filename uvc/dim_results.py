#!/usr/bin/env python3
"""Summarise a `probe.py dimsweep` log into Markdown tables, per camera (never pooled).
Reads the log only; opens no camera.

    uvc/.venv/bin/python -I uvc/dim_results.py uvc/logs/dimtestresults/dim-sweep-run1.log
"""
import re
import sys

STREAM = re.compile(
    r"stream \[(?P<label>[^\]]*?)(?: \(write[^)]*\))?\] [\d.]+s: frames=(?P<frames>\d+) "
    r"failed_reads=(?P<failed>\d+) fps=(?P<fps>[\d.]+) mean_brightness=(?P<bright>[\d.]+) "
    r"Y mean=(?P<ymean>[\d.]+) p1/p50/p99/max=(?P<p1>\d+)/(?P<p50>\d+)/(?P<p99>\d+)/(?P<ymax>\d+) "
    r"noise=(?P<noise>[\d.]+) snr=(?P<snr>[\d.]+) ge240=(?P<ge240>[\d.]+)% ge250=(?P<ge250>[\d.]+)% "
    r"black=(?P<black>[\d.]+)%")
INDEX = re.compile(r"^index (\d+) is kind (\w) at (0x[0-9a-f]+).*?brightness ([\d.]+) -> ([\d.]+) with the (\w+) marker")
SWEEP = re.compile(r"GAIN SWEEP: index (\d+)")


def parse(path):
    cams, cur = [], None
    for line in open(path, encoding="utf-8", errors="replace"):
        m = INDEX.match(line)
        if m:
            cur = {"index": int(m[1]), "kind": m[2], "loc": m[3], "marker": f"{m[6]} ({m[4]} -> {m[5]})",
                   "rows": {}}
            cams.append(cur)
            continue
        m = STREAM.search(line)
        if m and cur is not None and not m["label"].startswith(("identify", "warm-up")):
            cur["rows"][m["label"].replace(",", "")] = m.groupdict()
    return cams


def table(rows, keys, cols):
    out = ["| step | " + " | ".join(c for c, _ in cols) + " |", "|---" * (len(cols) + 1) + "|"]
    for k in keys:
        r = rows.get(k)
        if r:
            out.append(f"| {k} | " + " | ".join(f(r) for _, f in cols) + " |")
    return out


COLS = [("Y mean", lambda r: r["ymean"]), ("p1/p50/p99/max", lambda r: f'{r["p1"]}/{r["p50"]}/{r["p99"]}/{r["ymax"]}'),
        ("noise", lambda r: r["noise"]), ("snr", lambda r: r["snr"]), ("ge240 %", lambda r: r["ge240"]),
        ("ge250 %", lambda r: r["ge250"]), ("black %", lambda r: r["black"]), ("fps", lambda r: r["fps"])]


def main(path):
    cams = parse(path)
    print(f"<!-- generated by uvc/dim_results.py from {path} -->")
    keys = ["auto (before)"] + [f"{e} ms gain {g}" for e in (2, 3, 4, 10) for g in (0, 50, 100)] + ["auto (after)"]
    for c in sorted(cams, key=lambda c: c["loc"]):
        print(f"\n### Camera at {c['loc']} (kind {c['kind']}, index {c['index']}; marker {c['marker']})\n")
        print("\n".join(table(c["rows"], keys, COLS)))
    # one cross-camera view per measure, cameras side by side (not pooled)
    full = [f"{e} ms gain {g}" for e in (2, 3, 4, 10) for g in range(0, 101, 10)]
    cs = sorted(cams, key=lambda c: c["loc"])
    for name, field in (("Y mean", "ymean"), ("noise", "noise"), ("black %", "black"), ("ge250 %", "ge250")):
        print(f"\n### {name}, every step, per camera\n")
        print("| step | " + " | ".join(c["loc"] for c in cs) + " |")
        print("|---" * (len(cs) + 1) + "|")
        for k in ["auto (before)"] + full + ["auto (after)"]:
            print(f"| {k} | " + " | ".join(c["rows"].get(k, {}).get(field, "–") for c in cs) + " |")
    n = sum(len(c["rows"]) for c in cams)
    fps = [float(r["fps"]) for c in cams for r in c["rows"].values()]
    fails = sum(int(r["failed"]) for c in cams for r in c["rows"].values())
    print(f"\n<!-- {len(cams)} cameras, {n} rows, fps {min(fps)}-{max(fps)}, failed_reads total {fails} -->")


if __name__ == "__main__":
    main(sys.argv[1])
